# Local status constants (guarded to ensure membership in WORKFLOW_STATUS_VALUES)
STATUS_REVIEW_COMPLETE: str = "review_complete"
STATUS_DEBUG_REQUIRED: str = "debug_required"
STATUS_ESCALATION_REQUIRED: str = "escalation_required"
if (
    STATUS_REVIEW_COMPLETE not in WORKFLOW_STATUS_VALUES
    or STATUS_DEBUG_REQUIRED not in WORKFLOW_STATUS_VALUES
    or STATUS_ESCALATION_REQUIRED not in WORKFLOW_STATUS_VALUES
):
    raise ImportError("Local status constant is not a valid workflow status")

# Local mapping for rejection scope targets (Decision 5: no workflows/ imports)
REJECTION_SCOPE_MAP: Dict[str, str] = {
    "code_level": "DebugAgent",
    "design_level": "ArchitectAgent",
    "requirements_level": "ProductManagerAgent",
}

_DEFAULT_PROMPTS_DIR = Path(__file__).resolve().parent.parent / "prompts" / "reviewer"


def _now_iso() -> str:
    """Return the current UTC timestamp formatted as an ISO 8601 string."""
    return datetime.now(timezone.utc).isoformat()


class ReviewerOutput(BaseModel):
    """Structured review model generated by ReviewerAgent LLM."""

    overall_status: Literal["approved", "requires_changes", "rejected"] = Field(
        description="Overall review outcome: approved, requires_changes, or rejected"
    )
    code_quality_score: float = Field(
        ge=0.0,
        le=10.0,
        description="Quality rating between 0.0 and 10.0",
    )
    architecture_compliance: bool = Field(
        description="Strict compliance with SystemArchitecture specifications"
    )
    engineering_standards_compliance: bool = Field(
        description="Strict compliance with best practices and coding standards"
    )
    security_findings: List[str] = Field(
        default_factory=list,
        description="Security vulnerabilities, risks, or unsafe practices",
    )
    performance_findings: List[str] = Field(
        default_factory=list,
        description="Performance bottlenecks, inefficiencies, or leaks",
    )
    maintainability_findings: List[str] = Field(
        default_factory=list,
        description="Maintainability, complexity, or readability issues",
    )
    recommendations: List[str] = Field(
        default_factory=list,
        description="Actionable recommendations for fixing or improving code",
    )
    testing_coverage_assessment: str = Field(
        default="",
        description="Assessment of test coverage and test plan adequacy",
    )
    rejection_scope: Optional[str] = Field(
        default=None,
        description="Scope required if overall_status is 'rejected' (code_level, design_level, requirements_level). Must be None otherwise.",
    )
    summary: str = Field(
        default="",
        description="Executive summary of the code review",
    )


class ReviewerAgent(BaseAgent):
    """Concrete agent that performs holistic code review and assigns review status."""

    def __init__(
        self,
        model_name: str,
        llm_client: LLMClient,
        static_analyzer: StaticAnalysisTool,
        coverage_reader: CoverageReportReader,
        max_retries: int = DEFAULT_MAX_RETRIES,
        sleep_fn: Callable[[float], None] = time.sleep,
        prompts_dir: Optional[Union[Path, str]] = None,
    ) -> None:
        """
        Args:
            model_name: Model identifier (e.g. from configs/agents.yaml).
            llm_client: Structured LLM client conforming to LLMClient Protocol.
            static_analyzer: Required static code analysis tool (Protocol).
            coverage_reader: Required coverage report reader tool (Protocol).
            max_retries: Default retry ceiling passed to BaseAgent constructor.
            sleep_fn: Injectable sleep function for backoff timing.
            prompts_dir: Directory containing prompt templates (defaults to prompts/reviewer).
        """
        if not model_name or not isinstance(model_name, str) or not model_name.strip():
            raise ValueError("ReviewerAgent: model_name must be a non-empty string")
        if llm_client is None:
            raise ValueError("ReviewerAgent: llm_client must not be None")
        if static_analyzer is None:
            raise ValueError("ReviewerAgent: static_analyzer must not be None")
        if coverage_reader is None:
            raise ValueError("ReviewerAgent: coverage_reader must not be None")

        super().__init__(agent_name="ReviewerAgent", max_retries=max_retries)
        self.model_name = model_name
        self.llm_client = llm_client
        self.static_analyzer: StaticAnalysisTool = static_analyzer
        self.coverage_reader: CoverageReportReader = coverage_reader
        self.sleep_fn = sleep_fn
        self.prompts_dir = Path(prompts_dir) if prompts_dir else _DEFAULT_PROMPTS_DIR

    def _load_prompt(self, filename: str) -> str:
        """Read a prompt file and strip its metadata header block."""
        filepath = self.prompts_dir / filename
        if not filepath.exists():
            raise FileNotFoundError(f"Prompt template file not found: {filepath}")
        raw_text = filepath.read_text(encoding="utf-8")
        return strip_metadata_header(raw_text)

    def _get_effective_max_retries(self, state: EngineeringState) -> int:
        """Resolve effective max retries ceiling for ReviewerAgent."""
        max_retries_map = state.get("max_retries") or {}
        limit = max_retries_map.get(self.agent_name, self.max_retries)
        try:
            val = int(limit)
            return val if val > 0 else DEFAULT_MAX_RETRIES
        except (TypeError, ValueError):
            return DEFAULT_MAX_RETRIES

    def execute(self, state: EngineeringState) -> Dict[str, Any]:
        """Execute static analysis, coverage evaluation, and LLM review to generate ReviewReport."""
        started_at = _now_iso()
        effective_max = self._get_effective_max_retries(state)
        current_retries = (state.get("retry_counts") or {}).get(self.agent_name, 0)

        # 1. Fast-fail if retry limit already reached prior to execution
        if current_retries >= effective_max:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="retry_exhausted",
                error_message=(
                    f"Retry limit already reached ({current_retries}/{effective_max}) "
                    f"for {self.agent_name} before execution."
                ),
                traceback_str="",
                attempt_count=0,
            )

        requirements = state.get("requirements")
        architecture = state.get("architecture")
        code_artifacts = state.get("code_artifacts")
        test_artifacts = state.get("test_artifacts") or {}
        test_plan = state.get("test_plan")

        # 2. Fast-fail if mandatory inputs are missing
        if requirements is None or architecture is None or not code_artifacts:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="validation_failure",
                error_message="Missing or empty requirements, architecture, or code_artifacts",
                traceback_str="",
                attempt_count=0,
            )

        # 3. Call tools outside the LLM retry loop (Decision 7)
        # Any tool exception routes directly to exhaustion without LLM regeneration.
        try:
            static_report: StaticAnalysisReport = self.static_analyzer.analyze_code(
                code_artifacts=code_artifacts
            )
        except Exception as exc:
            import traceback

            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="unhandled_exception",
                error_message=f"Static analysis failed: {exc}",
                traceback_str=traceback.format_exc(),
                attempt_count=0,
            )

        try:
            coverage_report: CoverageReport = self.coverage_reader.read_coverage(
                test_plan=test_plan,
                test_artifacts=test_artifacts,
            )
        except Exception as exc:
            import traceback

            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="unhandled_exception",
                error_message=f"Coverage report reading failed: {exc}",
                traceback_str=traceback.format_exc(),
                attempt_count=0,
            )

        system_prompt = self._load_prompt("system_prompt.md")
        user_prompt_template = self._load_prompt("user_prompt_template.md")
        revision_prompt_template = self._load_prompt("revision_prompt.md")

        remaining_attempts = max(1, effective_max - current_retries)
        last_error_message = ""
        last_error_type = "validation_failure"
        last_traceback = ""
        attempt = 0

        # Build context strings for prompts
        project_name = state.get("project_name", "")
        code_summary = "\n".join(
            f"File: {path} ({art.artifact_type}/{art.language}, v{art.version}):\n{art.content}\n"
            for path, art in sorted(code_artifacts.items())
        )
        test_summary = (
            "\n".join(
                f"Test File: {path} ({art.test_type}, target: {art.coverage_target}, v{art.version}):\n{art.content}\n"
                for path, art in sorted(test_artifacts.items())
            )
            if test_artifacts
            else "No test artifacts provided."
        )
        test_plan_str = (
            str(test_plan.model_dump())
            if hasattr(test_plan, "model_dump")
            else str(test_plan)
        )
        arch_str = (
            str(architecture.model_dump())
            if hasattr(architecture, "model_dump")
            else str(architecture)
        )
        reqs_str = (
            str(requirements.model_dump())
            if hasattr(requirements, "model_dump")
            else str(requirements)
        )
        errors_history = "\n".join(
            f"- [{e.error_id}] ({e.agent}, {e.stage}): {e.message} (resolved={e.resolved})"
            for e in (state.get("errors") or [])
        ) or "None"

        initial_user_prompt = user_prompt_template.format(
            project_name=project_name,
            requirements=reqs_str,
            architecture=arch_str,
            test_plan=test_plan_str,
            static_passed=static_report.passed,
            static_complexity=static_report.complexity_score,
            static_security_warnings=", ".join(static_report.security_warnings) or "None",
            static_maintainability_warnings=", ".join(static_report.maintainability_warnings) or "None",
            static_issues=", ".join(static_report.issues) or "None",
            coverage_percentage=coverage_report.coverage_percentage,
            uncovered_files=", ".join(coverage_report.uncovered_files) or "None",
            coverage_summary=coverage_report.summary,
            errors_history=errors_history,
            code_artifacts=code_summary,
            test_artifacts=test_summary,
        )

        reviewer_output: Optional[ReviewerOutput] = None

        # 4. LLM retry loop
        while attempt < remaining_attempts:
            if attempt == 0:
                current_prompt = initial_user_prompt
            else:
                current_prompt = revision_prompt_template.format(
                    error_message=last_error_message,
                    project_name=project_name,
                    requirements=reqs_str,
                    architecture=arch_str,
                    static_analysis=f"Passed: {static_report.passed}, Issues: {static_report.issues}",
                    coverage_report=f"Coverage: {coverage_report.coverage_percentage}%, Summary: {coverage_report.summary}",
                    code_artifacts=code_summary,
                    test_artifacts=test_summary,
                )

            try:
                candidate: ReviewerOutput = self.llm_client.generate_structured(
                    prompt=current_prompt,
                    system_prompt=system_prompt,
                    response_model=ReviewerOutput,
                    model_name=self.model_name,
                )

                # Decision 6: Validate inside LLM retry loop:
                # rejected requires a valid scope; approved and requires_changes must have none.
                if candidate.overall_status == "rejected":
                    if (
                        not candidate.rejection_scope
                        or candidate.rejection_scope not in REJECTION_SCOPE_MAP
                    ):
                        raise ValueError(
                            f"ReviewerOutput: overall_status is 'rejected' but rejection_scope is invalid: "
                            f"{candidate.rejection_scope!r}. Must be one of {sorted(REJECTION_SCOPE_MAP.keys())}."
                        )
                else:
                    if candidate.rejection_scope is not None and candidate.rejection_scope != "":
                        raise ValueError(
                            f"ReviewerOutput: overall_status is {candidate.overall_status!r} but rejection_scope "
                            f"was provided: {candidate.rejection_scope!r}. rejection_scope must be None for approved or requires_changes."
                        )

                reviewer_output = candidate
                break

            except Exception as exc:
                attempt += 1
                last_error_message = str(exc)
                is_validation = isinstance(exc, (ValueError, TypeError))
                last_error_type = (
                    "validation_failure" if is_validation else "unhandled_exception"
                )
                import traceback

                last_traceback = traceback.format_exc()

                if attempt < remaining_attempts and not is_validation:
                    backoff_delay = 2.0 ** attempt
                    self.sleep_fn(backoff_delay)

        # 5. Handle exhaustion if LLM fails
        if reviewer_output is None:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type=last_error_type,
                error_message=(
                    f"Exhausted {remaining_attempts} attempts without valid review output. "
                    f"Last error ({last_error_type}): {last_error_message}"
                ),
                traceback_str=last_traceback,
                attempt_count=attempt,
            )

        # 6. Build success return
        return self._build_success_return(
            state=state,
            started_at=started_at,
            output=reviewer_output,
            attempt_count=attempt + 1,
        )

    def _build_success_return(
        self,
        state: EngineeringState,
        started_at: str,
        output: ReviewerOutput,
        attempt_count: int,
    ) -> Dict[str, Any]:
        """Assemble partial state update on successful review evaluation."""
        completed_at = _now_iso()

        # Version bump on re-review
        existing_report = state.get("review_report")
        if existing_report is not None:
            existing_ver = getattr(existing_report, "version", 1)
            if existing_ver is None and isinstance(existing_report, dict):
                existing_ver = existing_report.get("version", 1)
            report_version = (existing_ver or 1) + 1
        else:
            report_version = 1

        review_report = ReviewReport(
            overall_status=output.overall_status,
            code_quality_score=output.code_quality_score,
            architecture_compliance=output.architecture_compliance,
            engineering_standards_compliance=output.engineering_standards_compliance,
            security_findings=output.security_findings,
            performance_findings=output.performance_findings,
            maintainability_findings=output.maintainability_findings,
            recommendations=output.recommendations,
            testing_coverage_assessment=output.testing_coverage_assessment,
            produced_by=self.agent_name,
            produced_at=completed_at,
            version=report_version,
        )

        # Decision 9: Reset retry_counts["ReviewerAgent"] = 0 on all three outcomes
        updated_retry_counts = dict(state.get("retry_counts") or {})
        updated_retry_counts[self.agent_name] = 0

        duration = (
            datetime.fromisoformat(completed_at) - datetime.fromisoformat(started_at)
        ).total_seconds()
        metadata = AgentExecutionMetadata(
            agent_name=self.agent_name,
            started_at=started_at,
            completed_at=completed_at,
            duration_seconds=duration,
            tokens_used=0,
            model_calls=attempt_count,
            status="completed",
            notes=f"Review completed with status {output.overall_status}",
        )

        scratchpad_summary = {
            "overall_status": output.overall_status,
            "code_quality_score": output.code_quality_score,
            "security_findings_count": len(output.security_findings),
            "recommendations_count": len(output.recommendations),
            "summary": output.summary,
        }

        base_return: Dict[str, Any] = {
            "review_report": review_report,
            "current_agent": self.agent_name,
            "retry_counts": updated_retry_counts,
            "execution_metadata": {self.agent_name: metadata},
            "agent_scratchpad": {self.agent_name: str(scratchpad_summary)},
            "state_version": state.get("state_version", 0) + 1,
            "updated_at": completed_at,
        }

        # Outcome 1: approved
        if output.overall_status == "approved":
            current_forward_stage = state.get("forward_stage", 0)
            new_forward_stage = max(current_forward_stage, 7)
            base_return.update(
                {
                    "workflow_status": STATUS_REVIEW_COMPLETE,
                    "next_agent": "DevOpsAgent",
                    "forward_stage": new_forward_stage,
                    "checkpoint_stage": "review_complete",
                    "checkpoints": {"review_complete": completed_at},
                }
            )

        # Outcome 2: requires_changes
        elif output.overall_status == "requires_changes":
            err_id = str(uuid.uuid4())
            findings = (
                output.security_findings
                + output.performance_findings
                + output.maintainability_findings
            )
            findings_str = "; ".join(findings) if findings else "Code review requires changes"
            recs_str = (
                "; ".join(output.recommendations)
                if output.recommendations
                else "See review report"
            )
            err_msg = f"review_requires_changes: {findings_str}. Recommendations: {recs_str}"[:2000]

            err_record = ErrorRecord(
                error_id=err_id,
                agent=self.agent_name,
                stage=STATUS_DEBUG_REQUIRED,
                error_type="other",
                message=err_msg,
                occurred_at=completed_at,
                resolved=False,
            )
            base_return.update(
                {
                    "workflow_status": STATUS_DEBUG_REQUIRED,
                    "next_agent": "DebugAgent",
                    "errors": [err_record],
                    "current_debug_target": err_id,
                }
            )

        # Outcome 3: rejected
        elif output.overall_status == "rejected":
            target_agent = REJECTION_SCOPE_MAP[output.rejection_scope]
            reasons = (
                output.recommendations
                + output.security_findings
                + output.maintainability_findings
            )
            reasons_str = "; ".join(reasons) if reasons else "Code rejected during review"
            human_notes = (
                f"ReviewerAgent rejected code (scope: {output.rejection_scope}, "
                f"score: {output.code_quality_score}/10.0): {reasons_str}"
            )
            base_return.update(
                {
                    "workflow_status": STATUS_ESCALATION_REQUIRED,
                    "next_agent": target_agent,
                    "human_approval_required": True,
                    "human_approval_notes": human_notes,
                    "rejection_scope": output.rejection_scope,
                }
            )
            if output.rejection_scope == "code_level":
                err_id = str(uuid.uuid4())
                err_record = ErrorRecord(
                    error_id=err_id,
                    agent=self.agent_name,
                    stage=STATUS_DEBUG_REQUIRED,
                    error_type="other",
                    message=f"reviewer_rejected: {reasons_str}"[:2000],
                    occurred_at=completed_at,
                    resolved=False,
                )
                base_return["errors"] = [err_record]
                base_return["current_debug_target"] = err_id

        return base_return

    def _build_exhaustion_return(
        self,
        state: EngineeringState,
        started_at: str,
        error_type: str,
        error_message: str,
        traceback_str: str,
        attempt_count: int,
    ) -> Dict[str, Any]:
        """Build exhaustion state update triggering HumanApprovalNode pause."""
        completed_at = _now_iso()
        effective_max = self._get_effective_max_retries(state)

        updated_retry_counts = dict(state.get("retry_counts") or {})
        updated_retry_counts[self.agent_name] = effective_max

        human_notes = (
            f"ReviewerAgent failed after reaching max retries ({effective_max}). "
            f"Reason: {error_message}. Human approval is required to continue."
        )

        error_record = ErrorRecord(
            error_id=str(uuid.uuid4()),
            agent=self.agent_name,
            stage=str(state.get("workflow_status") or "review_exhaustion"),
            error_type="retry_exhausted",
            message=error_message,
            traceback=traceback_str,
            occurred_at=completed_at,
            resolved=False,
        )

        duration = (
            datetime.fromisoformat(completed_at) - datetime.fromisoformat(started_at)
        ).total_seconds()

        metadata = AgentExecutionMetadata(
            agent_name=self.agent_name,
            started_at=started_at,
            completed_at=completed_at,
            duration_seconds=duration,
            tokens_used=0,
            model_calls=attempt_count,
            status="failed",
            notes=error_message,
        )

        # Invariant: workflow_status is preserved unchanged
        return {
            "current_agent": self.agent_name,
            "next_agent": self.agent_name,
            "human_approval_required": True,
            "human_approval_notes": human_notes,
            "errors": [error_record],
            "retry_counts": updated_retry_counts,
            "execution_metadata": {self.agent_name: metadata},
            "agent_scratchpad": {self.agent_name: f"Exhaustion: {error_message}"},
            "state_version": state.get("state_version", 0) + 1,
            "updated_at": completed_at,
        }
