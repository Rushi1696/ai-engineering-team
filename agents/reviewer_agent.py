"""
agents/reviewer_agent.py

ReviewerAgent: The eighth concrete pipeline agent, performing holistic code review
across code artifacts, test artifacts, test plan, and architecture specifications.

Source of truth:
  - design.md Section 1.8 (ReviewerAgent Contract)
  - design.md Section 4.8 (ReviewerAgent Router Table)
  - design.md Section 6.1 (Folder ownership)
  - workflow-design-revised.md Section 3.6 (Reviewer -> Debug -> Developer Loop)
  - requirements.md Requirement 9 (ReviewReport), Requirement 13 (Retry & Escalation),
    Requirement 21 (Workflow Control)

Reviewer loop termination conditions (verbatim from workflow-design-revised.md Section 3.6):
| Condition | Action | Code / Router Mapping |
| `total_debug_cycles >= max_debug_cycles` | `workflow_status = "failed"` -> `END` | routers._check_common_precedence P2 -> NODE_GLOBAL_CAP_HANDLER -> failed -> END |
| `pipeline_deadline_at` exceeded | `deadline_enforcer` -> `END` | routers._check_common_precedence P1 -> NODE_DEADLINE_ENFORCER -> END |
| `review_report.overall_status == "approved"` | -> `devops` | ReviewerAgent sets workflow_status="review_complete", router_after_reviewer -> NODE_DEVOPS |
| `retry_counts["ReviewerAgent"] >= max_retries["ReviewerAgent"]` | `human_approval_required = True` -> `human_approval` | ReviewerAgent exhaustion returns human_approval_required=True, routers._check_common_precedence P3 -> NODE_HUMAN_APPROVAL |
| `rejected` + human rejects | `workflow_status = "failed"` -> `END` | human_approval_node sets workflow_status="failed", router_after_human_approval -> END |

Deterministic override note:
  Neither design.md Section 1.8 nor requirements.md specifies any deterministic override
  of the LLM's overall_status. Therefore, none is added.
"""

