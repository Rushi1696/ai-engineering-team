# Local status constants (guarded by test_architecture_rules to ensure membership in WORKFLOW_STATUS_VALUES)
STATUS_DEBUG_REQUIRED: str = "debug_required"
STATUS_FAILED: str = "failed"
if STATUS_DEBUG_REQUIRED not in WORKFLOW_STATUS_VALUES or STATUS_FAILED not in WORKFLOW_STATUS_VALUES:
    raise ImportError("Local status constant is not a valid workflow status")

_DEFAULT_PROMPTS_DIR = Path(__file__).resolve().parent.parent / "prompts" / "debug"


def _now_iso() -> str:
    """Return the current UTC timestamp formatted as an ISO 8601 string."""
    return datetime.now(timezone.utc).isoformat()


class DebugResolution(BaseModel):
    """Structured resolution model generated by DebugAgent LLM."""

    root_cause_analysis: str = Field(
        description="Detailed root-cause analysis explaining why the failure occurred"
    )
    hypothesis: str = Field(
        description="Hypothesis tested and verified for the proposed fix"
    )
    corrected_code_artifacts: List[CodeArtifact] = Field(
        default_factory=list,
        description="Patched or corrected CodeArtifact entries",
    )
    corrected_test_artifacts: List[TestArtifact] = Field(
        default_factory=list,
        description="Patched or corrected TestArtifact entries",
    )
    target_agent: Literal[
        "BackendAgent",
        "FrontendAgent",
        "QAAgent",
        "ReviewerAgent",
        "DevOpsAgent",
        "ArchitectAgent",
        "ProductManagerAgent",
    ] = Field(
        description="Next agent to execute after DebugAgent fix is applied"
    )
    resolution_notes: str = Field(
        description="Summary of resolution and notes for downstream agent"
    )


class DebugAgent(BaseAgent):
    """Concrete agent that diagnoses errors, generates corrected artifacts, and routes execution."""

    def __init__(
        self,
        model_name: str,
        llm_client: LLMClient,
        sandbox: CodeExecutionSandbox,
        log_parser: Optional[ErrorLogParser] = None,
        max_retries: int = DEFAULT_MAX_RETRIES,
        sleep_fn: Callable[[float], None] = time.sleep,
        prompts_dir: Optional[Union[Path, str]] = None,
    ) -> None:
        """
        Args:
            model_name: Model identifier (e.g. from configs/agents.yaml).
            llm_client: Structured LLM client implementation conforming to LLMClient Protocol.
            sandbox: Code execution sandbox for verifying candidate fixes in isolation (required).
            log_parser: Error log parser for extracting structured traceback and failure data.
            max_retries: Default retry ceiling passed to BaseAgent constructor.
            sleep_fn: Injectable sleep function for backoff timing (defaults to time.sleep).
            prompts_dir: Directory containing prompt templates (defaults to prompts/debug).
        """
        if not model_name or not isinstance(model_name, str) or not model_name.strip():
            raise ValueError("DebugAgent: model_name must be a non-empty string")
        if llm_client is None:
            raise ValueError("DebugAgent: llm_client must not be None")
        if sandbox is None:
            raise ValueError("DebugAgent: sandbox must not be None")

        super().__init__(agent_name="DebugAgent", max_retries=max_retries)
        self.model_name = model_name
        self.llm_client = llm_client
        self.sandbox: CodeExecutionSandbox = sandbox
        self.log_parser: ErrorLogParser = (
            log_parser if log_parser is not None else RegexLogParser()
        )
        self.sleep_fn = sleep_fn
        self.prompts_dir = Path(prompts_dir) if prompts_dir else _DEFAULT_PROMPTS_DIR

    def _load_prompt(self, filename: str) -> str:
        """Read a prompt file and strip its metadata header block."""
        filepath = self.prompts_dir / filename
        if not filepath.exists():
            raise FileNotFoundError(f"Prompt template file not found: {filepath}")
        raw_text = filepath.read_text(encoding="utf-8")
        return strip_metadata_header(raw_text)

    def _get_effective_max_retries(self, state: EngineeringState) -> int:
        """Resolve effective max retries ceiling for DebugAgent."""
        max_retries_map = state.get("max_retries") or {}
        limit = max_retries_map.get(self.agent_name, self.max_retries)
        try:
            val = int(limit)
            return val if val > 0 else DEFAULT_MAX_RETRIES
        except (TypeError, ValueError):
            return DEFAULT_MAX_RETRIES

    def execute(self, state: EngineeringState) -> Dict[str, Any]:
        """Execute root-cause analysis, verify candidate fix in sandbox, and build state update."""
        started_at = _now_iso()
        effective_max = self._get_effective_max_retries(state)
        current_retries = (state.get("retry_counts") or {}).get(self.agent_name, 0)

        # Fast-fail if retry limit already reached prior to execution
        if current_retries >= effective_max:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="retry_exhausted",
                error_message=(
                    f"Retry limit already reached ({current_retries}/{effective_max}) "
                    f"for {self.agent_name} before execution."
                ),
                traceback_str="",
                attempt_count=0,
            )

        # 1. Identify target ErrorRecord using current_debug_target first, then unresolved_errors
        errors: List[ErrorRecord] = state.get("errors") or []
        unresolved: List[ErrorRecord] = unresolved_errors(errors)

        target_error: Optional[ErrorRecord] = None
        raw_target_id = state.get("current_debug_target")
        # Use current_debug_target first (latest copy by error_id)
        if raw_target_id:
            for err in reversed(errors):
                if err.error_id == raw_target_id:
                    target_error = err
                    break

        # Fall back to the last unresolved error of a type other than "retry_exhausted"
        if target_error is None:
            actionable_unresolved = [
                err for err in unresolved if err.error_type != "retry_exhausted"
            ]
            if actionable_unresolved:
                target_error = actionable_unresolved[-1]

        review_report: Optional[ReviewReport] = state.get("review_report")
        if target_error is None:
            # Keep the Reviewer synthetic-record path only when no real target exists
            if (
                review_report is not None
                and getattr(review_report, "overall_status", None) == "requires_changes"
            ):
                recs = getattr(review_report, "recommendations", [])
                rec_summary = "; ".join(recs) if recs else "Reviewer requires changes"
                target_error = ErrorRecord(
                    error_id=str(uuid.uuid4()),
                    agent="ReviewerAgent",
                    stage=STATUS_DEBUG_REQUIRED,
                    error_type="other",
                    message=f"reviewer_requires_changes: {rec_summary}",
                    occurred_at=started_at,
                    resolved=False,
                )
            else:
                return self._build_exhaustion_return(
                    state=state,
                    started_at=started_at,
                    error_type="validation_failure",
                    error_message="DebugAgent: No unresolved errors or actionable review findings found in state",
                    traceback_str="",
                    attempt_count=0,
                )

        # 2. Use ErrorLogParser to parse the target error log (Decision 7)
        parsed_log: ParsedErrorLog = self.log_parser.parse_error_log(
            message=target_error.message,
            traceback=target_error.traceback,
        )

        # 3. Format context strings for prompt interpolation
        error_context = (
            f"Error ID: {target_error.error_id}\n"
            f"Originating Agent: {target_error.agent}\n"
            f"Stage: {target_error.stage}\n"
            f"Error Type: {target_error.error_type}\n"
            f"Exception Type: {parsed_log.exception_type}\n"
            f"Message: {parsed_log.error_message}\n"
            f"Failing Files: {', '.join(parsed_log.failing_files) if parsed_log.failing_files else 'None explicitly listed'}\n"
            f"Stack Trace / Frames:\n"
            + ("\n".join(parsed_log.stack_frames) if parsed_log.stack_frames else "None")
        )

        review_context = "None"
        if review_report is not None:
            # Decision 6: ReviewReport has no findings field; use specific findings & recommendations
            sec_f = getattr(review_report, "security_findings", [])
            perf_f = getattr(review_report, "performance_findings", [])
            maint_f = getattr(review_report, "maintainability_findings", [])
            recs = getattr(review_report, "recommendations", [])
            review_context = (
                f"Overall Status: {getattr(review_report, 'overall_status', '')}\n"
                f"Quality Score: {getattr(review_report, 'code_quality_score', 0.0)}\n"
                f"Security Findings:\n" + ("\n".join(f"- {f}" for f in sec_f) if sec_f else "None") + "\n"
                f"Performance Findings:\n" + ("\n".join(f"- {f}" for f in perf_f) if perf_f else "None") + "\n"
                f"Maintainability Findings:\n" + ("\n".join(f"- {f}" for f in maint_f) if maint_f else "None") + "\n"
                f"Recommendations:\n" + ("\n".join(f"- {r}" for r in recs) if recs else "None")
            )

        arch = state.get("architecture")
        arch_str = (
            str(arch.model_dump())
            if hasattr(arch, "model_dump")
            else str(arch or "Not provided")
        )

        task_plan = state.get("task_plan")
        tasks_summary = "None"
        if task_plan and getattr(task_plan, "tasks", None):
            tasks_summary = "\n".join(
                f"- [{t.task_id}] {t.title} ({t.assigned_agent}, status={t.status}): {t.description}"
                for t in task_plan.tasks
            )

        code_artifacts: Dict[str, CodeArtifact] = state.get("code_artifacts") or {}
        code_summary = (
            "\n".join(
                f"File: {path} ({art.artifact_type}/{art.language}, v{art.version}):\n{art.content}\n"
                for path, art in sorted(code_artifacts.items())
            )
            or "No code artifacts currently generated."
        )

        test_artifacts: Dict[str, TestArtifact] = state.get("test_artifacts") or {}
        test_summary = (
            "\n".join(
                f"File: {path} (v{art.version}):\n{art.content}\n"
                for path, art in sorted(test_artifacts.items())
            )
            or "No test artifacts currently generated."
        )

        system_prompt = self._load_prompt("system_prompt.md")
        user_prompt_template = self._load_prompt("user_prompt_template.md")
        revision_prompt_template = self._load_prompt("revision_prompt.md")

        user_prompt = user_prompt_template.format(
            project_name=state.get("project_name", "AI Project"),
            error_context=error_context,
            review_context=review_context,
            architecture=arch_str,
            tasks=tasks_summary,
            code_artifacts=code_summary,
            test_artifacts=test_summary,
            user_context=f"user_input: {state.get('user_input', '')}",
        )

        remaining_attempts = max(1, effective_max - current_retries)
        last_error_message = ""
        last_error_type = "validation_failure"
        last_traceback = ""
        attempt = 0
        resolution: Optional[DebugResolution] = None

        # 4. LLM Generation and Sandbox Verification Loop
        while attempt < remaining_attempts:
            prompt_to_use = user_prompt
            if attempt > 0:
                prompt_to_use = revision_prompt_template.format(
                    error_message=f"{last_error_type}: {last_error_message}",
                    project_name=state.get("project_name", "AI Project"),
                    error_context=error_context,
                    review_context=review_context,
                    architecture=arch_str,
                    tasks=tasks_summary,
                    code_artifacts=code_summary,
                    test_artifacts=test_summary,
                    user_context=f"user_input: {state.get('user_input', '')}",
                )

            try:
                candidate = self.llm_client.generate_structured(
                    prompt=prompt_to_use,
                    response_model=DebugResolution,
                    system_prompt=system_prompt,
                    model_name=self.model_name,
                )

                # Validation A: Must produce at least one corrected artifact
                if (
                    not candidate.corrected_code_artifacts
                    and not candidate.corrected_test_artifacts
                ):
                    raise ValueError(
                        "DebugAgent: Resolution produced neither corrected code artifacts nor test artifacts"
                    )

                # Validation B: Validate target_agent against 7 permitted values (Decision 4 & 5)
                validate_debug_agent_next_agent(
                    current_agent=self.agent_name,
                    next_agent_value=candidate.target_agent,
                )

                resolution = candidate
                break

            except Exception as exc:
                attempt += 1
                last_error_message = str(exc)
                is_validation = isinstance(exc, (ValueError, TypeError))
                last_error_type = (
                    "validation_failure" if is_validation else "unhandled_exception"
                )
                import traceback
                last_traceback = traceback.format_exc()

                # Exponential backoff sleep only for unhandled exceptions, not validation errors
                if attempt < remaining_attempts and not is_validation:
                    backoff_delay = 2.0 ** attempt
                    self.sleep_fn(backoff_delay)

        # 5. Handle exhaustion if LLM fails
        if resolution is None:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type=last_error_type,
                error_message=(
                    f"Exhausted {remaining_attempts} attempts without valid debug resolution. "
                    f"Last error ({last_error_type}): {last_error_message}"
                ),
                traceback_str=last_traceback,
                attempt_count=attempt,
            )

        # 6. Outside LLM retry loop: execute sandbox verification (item 4)
        # A sandbox exception goes straight to exhaustion without LLM regeneration.
        try:
            merged_code = dict(code_artifacts)
            for art in resolution.corrected_code_artifacts:
                merged_code[art.file_path] = art

            merged_tests = dict(test_artifacts)
            for art in resolution.corrected_test_artifacts:
                merged_tests[art.file_path] = art

            sandbox_result = self.sandbox.execute_in_sandbox(
                code_artifacts=merged_code,
                test_artifacts=merged_tests,
            )
            if not sandbox_result.passed:
                raise RuntimeError(
                    f"Sandbox verification failed (exit code {sandbox_result.exit_code}): "
                    f"{sandbox_result.output or sandbox_result.stderr}"
                )
        except Exception as exc:
            import traceback
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="sandbox_error",
                error_message=f"Sandbox execution failed: {exc}",
                traceback_str=traceback.format_exc(),
                attempt_count=attempt,
            )

        # 7. Build success return
        return self._build_success_return(
            state=state,
            started_at=started_at,
            resolution=resolution,
            target_error=target_error,
            code_artifacts=code_artifacts,
            test_artifacts=test_artifacts,
            attempt_count=attempt + 1,
        )

    def _build_success_return(
        self,
        state: EngineeringState,
        started_at: str,
        resolution: DebugResolution,
        target_error: ErrorRecord,
        code_artifacts: Dict[str, CodeArtifact],
        test_artifacts: Dict[str, TestArtifact],
        attempt_count: int,
    ) -> Dict[str, Any]:
        """Assemble partial state update on successful debug resolution."""
        completed_at = _now_iso()

        # 1. Update code artifacts with version increments
        updated_code_artifacts: Dict[str, CodeArtifact] = {}
        for art in resolution.corrected_code_artifacts:
            existing = code_artifacts.get(art.file_path)
            existing_ver = getattr(existing, "version", 1) if existing else 1
            if existing_ver is None and isinstance(existing, dict):
                existing_ver = existing.get("version", 1)
            art.version = (existing_ver or 1) + 1
            art.produced_by = self.agent_name
            art.produced_at = completed_at
            updated_code_artifacts[art.file_path] = art

        # 2. Update test artifacts with version increments
        updated_test_artifacts: Dict[str, TestArtifact] = {}
        for art in resolution.corrected_test_artifacts:
            existing = test_artifacts.get(art.file_path)
            existing_ver = getattr(existing, "version", 1) if existing else 1
            if existing_ver is None and isinstance(existing, dict):
                existing_ver = existing.get("version", 1)
            art.version = (existing_ver or 1) + 1
            art.produced_by = self.agent_name
            art.produced_at = completed_at
            updated_test_artifacts[art.file_path] = art

        # 3. Resolve target error by appending resolved copy (Decision 1)
        res_notes = (
            resolution.resolution_notes
            or f"Resolved by DebugAgent. RCA: {resolution.root_cause_analysis[:200]}"
        )
        resolved_record = target_error.model_copy(
            update={
                "resolved": True,
                "resolution_agent": self.agent_name,
                "resolution_notes": res_notes,
            }
        )

        # 4. total_debug_cycles increments only on completed fix attempt (Decision 8)
        current_cycles = state.get("total_debug_cycles", 0)
        new_cycles = current_cycles + 1

        # 5. Retry counts reset for DebugAgent on success; others preserved
        updated_retry_counts = dict(state.get("retry_counts") or {})
        updated_retry_counts[self.agent_name] = 0

        # 6. Execution metadata
        duration = (
            datetime.fromisoformat(completed_at) - datetime.fromisoformat(started_at)
        ).total_seconds()
        metadata = AgentExecutionMetadata(
            agent_name=self.agent_name,
            started_at=started_at,
            completed_at=completed_at,
            duration_seconds=duration,
            tokens_used=0,
            model_calls=attempt_count,
            status="completed",
            notes=f"Resolved error {target_error.error_id}. Routing to {resolution.target_agent}",
        )

        scratchpad_entry = (
            f"DebugAgent RCA: {resolution.root_cause_analysis[:200]} | "
            f"Hypothesis: {resolution.hypothesis[:150]} | "
            f"Target: {resolution.target_agent} | Cycles: {new_cycles}"
        )

        # Decision 4: workflow_status is left unchanged; sets only next_agent
        # Decision 2: Write "" to clear current_debug_target
        result: Dict[str, Any] = {
            "current_agent": self.agent_name,
            "next_agent": resolution.target_agent,
            "errors": [resolved_record],
            "current_debug_target": "",
            "total_debug_cycles": new_cycles,
            "retry_counts": updated_retry_counts,
            "agent_scratchpad": {self.agent_name: scratchpad_entry},
            "execution_metadata": {self.agent_name: metadata},
            "state_version": state.get("state_version", 0) + 1,
            "updated_at": completed_at,
        }

        if updated_code_artifacts:
            result["code_artifacts"] = updated_code_artifacts
        if updated_test_artifacts:
            result["test_artifacts"] = updated_test_artifacts

        return result

    def _build_exhaustion_return(
        self,
        state: EngineeringState,
        started_at: str,
        error_type: str,
        error_message: str,
        traceback_str: str,
        attempt_count: int,
    ) -> Dict[str, Any]:
        """Build exhaustion state update triggering HumanApprovalNode pause."""
        completed_at = _now_iso()
        effective_max = self._get_effective_max_retries(state)

        updated_retry_counts = dict(state.get("retry_counts") or {})
        updated_retry_counts[self.agent_name] = effective_max

        human_notes = (
            f"DebugAgent failed after reaching max retries ({effective_max}). "
            f"Reason: {error_message}. Human approval is required to continue."
        )

        error_record = ErrorRecord(
            error_id=str(uuid.uuid4()),
            agent=self.agent_name,
            stage=str(state.get("workflow_status") or "debug_exhaustion"),
            error_type="retry_exhausted",
            message=error_message,
            traceback=traceback_str,
            occurred_at=completed_at,
            resolved=False,
        )

        duration = (
            datetime.fromisoformat(completed_at) - datetime.fromisoformat(started_at)
        ).total_seconds()

        metadata = AgentExecutionMetadata(
            agent_name=self.agent_name,
            started_at=started_at,
            completed_at=completed_at,
            duration_seconds=duration,
            tokens_used=0,
            model_calls=attempt_count,
            status="failed",
            notes=error_message,
        )

        # Invariants:
        # - workflow_status preserved unchanged
        # - total_debug_cycles is NOT incremented on exhaustion (Decision 8)
        return {
            "current_agent": self.agent_name,
            "next_agent": self.agent_name,
            "human_approval_required": True,
            "human_approval_notes": human_notes,
            "errors": [error_record],
            "retry_counts": updated_retry_counts,
            "execution_metadata": {self.agent_name: metadata},
            "agent_scratchpad": {self.agent_name: f"Exhaustion: {error_message}"},
            "state_version": state.get("state_version", 0) + 1,
            "updated_at": completed_at,
        }

