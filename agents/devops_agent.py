"""
agents/devops_agent.py

DevOpsAgent: The ninth concrete pipeline agent, generating deployment and infrastructure
artifacts (Dockerfiles, CI/CD pipelines, compose files, monitoring configs).

Source of truth:
  - design.md Section 1.9 (DevOpsAgent Contract)
  - design.md Section 4.9 (DevOpsAgent Tools table)
  - design.md Section 6.1 (Folder ownership)
  - workflows/routers.py (router_after_devops)
  - requirements.md Requirement 9 (DeploymentArtifact), Requirement 13 (Retry & Escalation),
    Requirement 21 (Workflow Control)
"""

from __future__ import annotations

import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Dict, List, Literal, Optional, Union

from pydantic import BaseModel, Field

from agents.base_agent import BaseAgent, DEFAULT_MAX_RETRIES, strip_metadata_header
from state.engineering_state import EngineeringState
from state.models import (
    AgentExecutionMetadata,
    CodeArtifact,
    DeploymentArtifact,
    ErrorRecord,
    SystemArchitecture,
)
from state.validators import WORKFLOW_STATUS_VALUES
from tools.devops.yaml_validator import ConfigValidator, ValidationReport
from tools.shared.llm_client import LLMClient

# Local status constants (guarded to ensure membership in WORKFLOW_STATUS_VALUES)
STATUS_DEVOPS_COMPLETE: str = "devops_complete"
if STATUS_DEVOPS_COMPLETE not in WORKFLOW_STATUS_VALUES:
    raise ImportError("Local status constant is not a valid workflow status")

_DEFAULT_PROMPTS_DIR = Path(__file__).resolve().parent.parent / "prompts" / "devops"


def _now_iso() -> str:
    """Return the current UTC timestamp formatted as an ISO 8601 string."""
    return datetime.now(timezone.utc).isoformat()


class DraftDeploymentArtifact(BaseModel):
    """Draft deployment artifact generated by LLM prior to agent metadata stamping."""

    file_path: str = Field(description="Relative path of deployment artifact (e.g. Dockerfile)")
    content: str = Field(description="Complete, syntactically valid content of configuration file")
    artifact_type: Literal[
        "dockerfile",
        "docker_compose",
        "ci_cd_pipeline",
        "infrastructure_template",
        "deployment_script",
        "monitoring_config",
        "other",
    ] = Field(description="Category of deployment artifact")


class DevOpsOutput(BaseModel):
    """Structured container model for deployment artifacts returned by LLM."""

    artifacts: List[DraftDeploymentArtifact] = Field(
        default_factory=list,
        description="List of draft deployment artifacts",
    )
    summary: str = Field(
        default="",
        description="Summary of infrastructure architecture and deployment decisions",
    )


class DevOpsAgent(BaseAgent):
    """Concrete agent that generates and validates deployment infrastructure artifacts."""

    def __init__(
        self,
        model_name: str,
        llm_client: LLMClient,
        validator: ConfigValidator,
        max_retries: int = DEFAULT_MAX_RETRIES,
        sleep_fn: Callable[[float], None] = time.sleep,
        prompts_dir: Optional[Union[Path, str]] = None,
    ) -> None:
        """
        Args:
            model_name: Model identifier (e.g. from configs/agents.yaml).
            llm_client: Structured LLM client conforming to LLMClient Protocol.
            validator: Required configuration validation tool (Protocol).
            max_retries: Default retry ceiling passed to BaseAgent constructor.
            sleep_fn: Injectable sleep function for backoff timing.
            prompts_dir: Directory containing prompt templates (defaults to prompts/devops).
        """
        if not model_name or not isinstance(model_name, str) or not model_name.strip():
            raise ValueError("DevOpsAgent: model_name must be a non-empty string")
        if llm_client is None:
            raise ValueError("DevOpsAgent: llm_client must not be None")
        if validator is None:
            raise ValueError("DevOpsAgent: validator must not be None")

        super().__init__(agent_name="DevOpsAgent", max_retries=max_retries)
        self.model_name = model_name
        self.llm_client = llm_client
        self.validator: ConfigValidator = validator
        self.sleep_fn = sleep_fn
        self.prompts_dir = Path(prompts_dir) if prompts_dir else _DEFAULT_PROMPTS_DIR

    def _load_prompt(self, filename: str) -> str:
        """Read a prompt file and strip its metadata header block."""
        filepath = self.prompts_dir / filename
        if not filepath.exists():
            raise FileNotFoundError(f"Prompt template file not found: {filepath}")
        raw_text = filepath.read_text(encoding="utf-8")
        return strip_metadata_header(raw_text)

    def _get_effective_max_retries(self, state: EngineeringState) -> int:
        """Resolve effective max retries ceiling for DevOpsAgent."""
        max_retries_map = state.get("max_retries") or {}
        limit = max_retries_map.get(self.agent_name, self.max_retries)
        try:
            val = int(limit)
            return val if val > 0 else DEFAULT_MAX_RETRIES
        except (TypeError, ValueError):
            return DEFAULT_MAX_RETRIES

    def execute(self, state: EngineeringState) -> Dict[str, Any]:
        """Generate deployment artifacts, validate syntax, and route to Documentation or Debug."""
        started_at = _now_iso()
        effective_max = self._get_effective_max_retries(state)
        current_retries = (state.get("retry_counts") or {}).get(self.agent_name, 0)

        # 1. Fast-fail if retry limit already reached prior to execution
        if current_retries >= effective_max:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="retry_exhausted",
                error_message=(
                    f"Retry limit already reached ({current_retries}/{effective_max}) "
                    f"for {self.agent_name} before execution."
                ),
                traceback_str="",
                attempt_count=0,
            )

        architecture: Optional[SystemArchitecture] = state.get("architecture")
        code_artifacts: Optional[Dict[str, CodeArtifact]] = state.get("code_artifacts")

        # 2. Fast-fail if mandatory inputs are missing
        if architecture is None or not code_artifacts:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="validation_failure",
                error_message="Missing or empty architecture or code_artifacts",
                traceback_str="",
                attempt_count=0,
            )

        system_prompt = self._load_prompt("system_prompt.md")
        user_prompt_template = self._load_prompt("user_prompt_template.md")
        revision_prompt_template = self._load_prompt("revision_prompt.md")

        remaining_attempts = max(1, effective_max - current_retries)
        last_error_message = ""
        last_error_type = "validation_failure"
        last_traceback = ""
        last_artifacts_str = "None"
        attempt = 0

        # Build context strings for prompts
        project_name = state.get("project_name", "")
        tech_stack = (
            str(architecture.technology_stack)
            if hasattr(architecture, "technology_stack")
            else "Standard containerized stack"
        )
        arch_str = (
            str(architecture.model_dump())
            if hasattr(architecture, "model_dump")
            else str(architecture)
        )
        requirements = state.get("requirements")
        reqs_str = (
            str(requirements.model_dump())
            if hasattr(requirements, "model_dump")
            else str(requirements)
            if requirements
            else "None"
        )
        review_report = state.get("review_report")
        review_str = (
            str(review_report.model_dump())
            if hasattr(review_report, "model_dump")
            else str(review_report)
            if review_report
            else "None"
        )
        code_summary = "\n".join(
            f"File: {path} ({art.artifact_type}/{art.language})"
            for path, art in sorted(code_artifacts.items())
        )

        initial_user_prompt = user_prompt_template.format(
            project_name=project_name,
            architecture=arch_str,
            technology_stack=tech_stack,
            requirements=reqs_str,
            review_report=review_str,
            code_artifacts=code_summary,
        )

        existing_artifacts = state.get("deployment_artifacts") or {}
        devops_output: Optional[DevOpsOutput] = None
        validated_artifacts: Dict[str, DeploymentArtifact] = {}

        # 3. LLM retry loop
        while attempt < remaining_attempts:
            if attempt == 0:
                current_prompt = initial_user_prompt
            else:
                current_prompt = revision_prompt_template.format(
                    error_message=last_error_message,
                    previous_artifacts=last_artifacts_str,
                    project_name=project_name,
                    architecture=arch_str,
                    code_artifacts=code_summary,
                )

            try:
                candidate: DevOpsOutput = self.llm_client.generate_structured(
                    prompt=current_prompt,
                    system_prompt=system_prompt,
                    response_model=DevOpsOutput,
                    model_name=self.model_name,
                )

                # Validation inside retry loop:
                # Must contain at least one dockerfile and at least one ci_cd_pipeline (design.md Section 1.9)
                if not candidate.artifacts:
                    raise ValueError("DevOpsAgent: Generated artifacts list cannot be empty")

                has_dockerfile = any(a.artifact_type == "dockerfile" for a in candidate.artifacts)
                has_cicd = any(a.artifact_type == "ci_cd_pipeline" for a in candidate.artifacts)

                if not has_dockerfile or not has_cicd:
                    raise ValueError(
                        f"DevOpsAgent: Must produce at least one 'dockerfile' and one 'ci_cd_pipeline' artifact "
                        f"(got dockerfile={has_dockerfile}, ci_cd_pipeline={has_cicd})"
                    )

                for art in candidate.artifacts:
                    if not art.file_path or not art.file_path.strip():
                        raise ValueError("DevOpsAgent: Artifact file_path cannot be empty")
                    if not art.content or not art.content.strip():
                        raise ValueError(f"DevOpsAgent: Artifact content cannot be empty for {art.file_path}")

                # Record previous artifacts for revision prompt in case validator fails
                last_artifacts_str = "\n\n".join(
                    f"--- {art.file_path} ({art.artifact_type}) ---\n{art.content}"
                    for art in candidate.artifacts
                )

                # Build candidate DeploymentArtifact objects for validator
                timestamp = _now_iso()
                candidate_artifacts: Dict[str, DeploymentArtifact] = {}
                for draft in candidate.artifacts:
                    existing = existing_artifacts.get(draft.file_path)
                    existing_ver = getattr(existing, "version", 1) if existing else 1
                    if existing_ver is None and isinstance(existing, dict):
                        existing_ver = existing.get("version", 1)
                    version = (existing_ver or 1) + 1 if existing else 1

                    candidate_artifacts[draft.file_path] = DeploymentArtifact(
                        file_path=draft.file_path,
                        content=draft.content,
                        artifact_type=draft.artifact_type,
                        produced_by=self.agent_name,
                        produced_at=timestamp,
                        version=version,
                    )

                # Tool execution: a tool EXCEPTION bypasses LLM retry loop and goes straight to exhaustion
                try:
                    validation_report: ValidationReport = self.validator.validate_configs(
                        deployment_artifacts=candidate_artifacts
                    )
                except Exception as tool_exc:
                    import traceback

                    return self._build_exhaustion_return(
                        state=state,
                        started_at=started_at,
                        error_type="unhandled_exception",
                        error_message=f"Config validation tool exception: {tool_exc}",
                        traceback_str=traceback.format_exc(),
                        attempt_count=attempt,
                    )

                # Tool report failure: feeds LLM retry loop as a validation_failure
                if not validation_report.valid:
                    err_msg = "; ".join(validation_report.errors or ["Invalid configuration syntax"])
                    raise ValueError(f"Configuration validation failed: {err_msg}")

                # Success: valid output and report passed
                devops_output = candidate
                validated_artifacts = candidate_artifacts
                break

            except Exception as exc:
                attempt += 1
                last_error_message = str(exc)
                is_validation = isinstance(exc, (ValueError, TypeError))
                last_error_type = (
                    "validation_failure" if is_validation else "unhandled_exception"
                )
                import traceback

                last_traceback = traceback.format_exc()

                if attempt < remaining_attempts and not is_validation:
                    backoff_delay = 2.0 ** attempt
                    self.sleep_fn(backoff_delay)

        # 4. Handle exhaustion if LLM fails
        if devops_output is None:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type=last_error_type,
                error_message=(
                    f"Exhausted {remaining_attempts} attempts without valid DevOps artifacts. "
                    f"Last error ({last_error_type}): {last_error_message}"
                ),
                traceback_str=last_traceback,
                attempt_count=attempt,
            )

        completed_at = _now_iso()
        duration = (
            datetime.fromisoformat(completed_at) - datetime.fromisoformat(started_at)
        ).total_seconds()

        # 5. Success path
        current_forward_stage = state.get("forward_stage", 0)
        new_forward_stage = max(current_forward_stage, 8)
        updated_retry_counts = dict(state.get("retry_counts") or {})
        updated_retry_counts[self.agent_name] = 0

        metadata = AgentExecutionMetadata(
            agent_name=self.agent_name,
            started_at=started_at,
            completed_at=completed_at,
            duration_seconds=duration,
            tokens_used=0,
            model_calls=attempt + 1,
            status="completed",
            notes="Deployment artifacts successfully generated and validated",
        )

        return {
            "deployment_artifacts": validated_artifacts,
            "workflow_status": STATUS_DEVOPS_COMPLETE,
            "current_agent": self.agent_name,
            "next_agent": "DocumentationAgent",
            "forward_stage": new_forward_stage,
            "checkpoint_stage": "devops_complete",
            "checkpoints": {"devops_complete": completed_at},
            "retry_counts": updated_retry_counts,
            "execution_metadata": {self.agent_name: metadata},
            "agent_scratchpad": {self.agent_name: devops_output.summary or "Deployment artifacts generated"},
            "state_version": state.get("state_version", 0) + 1,
            "updated_at": completed_at,
        }

    def _build_exhaustion_return(
        self,
        state: EngineeringState,
        started_at: str,
        error_type: str,
        error_message: str,
        traceback_str: str,
        attempt_count: int,
    ) -> Dict[str, Any]:
        """Build exhaustion state update triggering HumanApprovalNode pause."""
        completed_at = _now_iso()
        effective_max = self._get_effective_max_retries(state)

        updated_retry_counts = dict(state.get("retry_counts") or {})
        updated_retry_counts[self.agent_name] = effective_max

        human_notes = (
            f"DevOpsAgent failed after reaching max retries ({effective_max}). "
            f"Reason: {error_message}. Human approval is required to continue."
        )

        error_record = ErrorRecord(
            error_id=str(uuid.uuid4()),
            agent=self.agent_name,
            stage=str(state.get("workflow_status") or "devops_exhaustion"),
            error_type="retry_exhausted",
            message=error_message,
            traceback=traceback_str,
            occurred_at=completed_at,
            resolved=False,
        )

        duration = (
            datetime.fromisoformat(completed_at) - datetime.fromisoformat(started_at)
        ).total_seconds()

        metadata = AgentExecutionMetadata(
            agent_name=self.agent_name,
            started_at=started_at,
            completed_at=completed_at,
            duration_seconds=duration,
            tokens_used=0,
            model_calls=attempt_count,
            status="failed",
            notes=error_message,
        )

        # Invariant: workflow_status is preserved unchanged
        return {
            "current_agent": self.agent_name,
            "next_agent": self.agent_name,
            "human_approval_required": True,
            "human_approval_notes": human_notes,
            "errors": [error_record],
            "retry_counts": updated_retry_counts,
            "execution_metadata": {self.agent_name: metadata},
            "agent_scratchpad": {self.agent_name: f"Exhaustion: {error_message}"},
            "state_version": state.get("state_version", 0) + 1,
            "updated_at": completed_at,
        }
