# Local status constants satisfying design.md Section 6 Rule 3 (no workflows/ imports)
STATUS_QA_COMPLETE = "qa_complete"
STATUS_DEBUG_REQUIRED = "debug_required"

_DEFAULT_PROMPTS_DIR = Path(__file__).resolve().parent.parent / "prompts" / "qa"


def _now_iso() -> str:
    """Current UTC time as an ISO 8601 string."""
    return datetime.now(timezone.utc).isoformat()


class QAResult(BaseModel):
    """Structured container of QA outputs generated by QAAgent."""

    model_config = ConfigDict(
        frozen=False, validate_assignment=True, populate_by_name=True
    )

    test_plan: TestPlan
    test_artifacts: List[TestArtifact] = Field(
        default_factory=list,
        validation_alias=AliasChoices("test_artifacts", "artifacts", "tests"),
    )
    ai_findings: List[str] = Field(
        default_factory=list,
        validation_alias=AliasChoices("ai_findings", "findings", "notes"),
    )

    @model_validator(mode="before")
    @classmethod
    def _prepare_qa_result(cls, data: Any) -> Any:
        if isinstance(data, dict):
            now = _now_iso()
            tp = data.get("test_plan")
            if isinstance(tp, dict):
                if not tp.get("produced_by"):
                    tp["produced_by"] = "QAAgent"
                if not tp.get("produced_at"):
                    tp["produced_at"] = now
                if "version" not in tp:
                    tp["version"] = 1
                if isinstance(tp.get("coverage_goals"), dict):
                    tp["coverage_goals"] = {
                        str(k): str(v) for k, v in tp["coverage_goals"].items()
                    }
                if isinstance(tp.get("test_suites"), list):
                    clean_suites = []
                    for item in tp["test_suites"]:
                        if isinstance(item, dict):
                            clean_suites.append(
                                item.get("name") or item.get("file_path") or str(item)
                            )
                        else:
                            clean_suites.append(str(item))
                    tp["test_suites"] = clean_suites

            raw_list = (
                data.get("test_artifacts")
                or data.get("artifacts")
                or data.get("tests")
                or []
            )
            prepared = []
            for item in raw_list:
                if isinstance(item, dict):
                    art_dict = dict(item)
                    if not art_dict.get("produced_by"):
                        art_dict["produced_by"] = "QAAgent"
                    if not art_dict.get("produced_at"):
                        art_dict["produced_at"] = now
                    if "test_type" not in art_dict:
                        art_dict["test_type"] = "unit"
                    if "version" not in art_dict:
                        art_dict["version"] = 1
                    if "coverage_target" in art_dict and not isinstance(
                        art_dict["coverage_target"], str
                    ):
                        art_dict["coverage_target"] = str(art_dict["coverage_target"])
                    prepared.append(art_dict)
                else:
                    prepared.append(item)
            data["test_artifacts"] = prepared
        return data


class QAAgent(BaseAgent):
    """QAAgent produces TestPlan and TestArtifact entries for all code in code_artifacts.

    Inherits from BaseAgent and implements execute() with an internal retry loop
    for validation errors and unhandled exceptions, executing tests via an injected
    TestRunner and conditionally routing to ReviewerAgent on pass or DebugAgent on failure.
    """

    def __init__(
        self,
        model_name: str,
        llm_client: LLMClient,
        test_runner: TestRunner,
        max_retries: int = DEFAULT_MAX_RETRIES,
        sleep_fn: Callable[[float], None] = time.sleep,
        prompts_dir: Optional[Union[Path, str]] = None,
    ) -> None:
        """
        Args:
            model_name: Model identifier (e.g. from configs/agents.yaml).
            llm_client: Structured LLM client implementation conforming to LLMClient Protocol.
            test_runner: REQUIRED test runner implementing TestRunner protocol.
            max_retries: Effective retry ceiling passed directly to BaseAgent constructor.
            sleep_fn: Injectable sleep function for backoff timing (defaults to time.sleep).
            prompts_dir: Directory containing prompt templates (defaults to prompts/qa).
        """
        if not model_name or not isinstance(model_name, str) or not model_name.strip():
            raise ValueError("QAAgent: model_name must be a non-empty string")
        if llm_client is None:
            raise ValueError("QAAgent: llm_client is required")
        if test_runner is None:
            raise ValueError("QAAgent: test_runner is required")

        super().__init__(agent_name="QAAgent", max_retries=max_retries)
        self.model_name = model_name
        self.llm_client = llm_client
        self.test_runner = test_runner
        self.sleep_fn = sleep_fn
        self.prompts_dir = Path(prompts_dir) if prompts_dir else _DEFAULT_PROMPTS_DIR

    def _load_prompt(self, filename: str) -> str:
        """Load markdown prompt template and strip metadata header block."""
        path = self.prompts_dir / filename
        if not path.is_file():
            raise FileNotFoundError(f"QAAgent prompt template not found: {path}")
        return strip_metadata_header(path.read_text(encoding="utf-8"))

    def execute(self, state: EngineeringState) -> Dict[str, Any]:
        """Execute QAAgent business logic against current EngineeringState.

        Validates inputs, generates QA plan and test artifacts via LLMClient,
        runs tests via TestRunner, and returns partial state update.
        """
        started_at = _now_iso()

        # Fast-fail if any prerequisite input is missing or empty
        requirements: Optional[ProductRequirements] = state.get("requirements")
        architecture: Optional[SystemArchitecture] = state.get("architecture")
        task_plan: Optional[TaskPlan] = state.get("task_plan")
        code_artifacts: Optional[Dict[str, CodeArtifact]] = state.get("code_artifacts")

        if (
            requirements is None
            or architecture is None
            or task_plan is None
            or not code_artifacts
            or not requirements.functional_requirements
            or not architecture.api_specifications
            or not task_plan.tasks
        ):
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="validation_failure",
                error_message="Missing or empty requirements, architecture, task_plan, or code_artifacts",
                traceback_str="",
                attempt_count=0,
            )

        system_prompt = self._load_prompt("system_prompt.md")
        user_prompt_template = self._load_prompt("user_prompt_template.md")
        revision_prompt_template = self._load_prompt("revision_prompt.md")

        effective_max_retries = self._get_effective_max_retries(state)
        current_qa_retries = (state.get("retry_counts") or {}).get(self.agent_name, 0)
        remaining_attempts = max(1, effective_max_retries - current_qa_retries)

        last_error_message = ""
        last_error_type = "validation_failure"
        last_traceback = ""
        attempt = 0

        # Build initial user prompt
        code_summary = "\n".join(
            f"File: {path} ({art.artifact_type}/{art.language}):\n{art.content}\n"
            for path, art in sorted(code_artifacts.items())
        )
        task_summary = "\n".join(
            f"- [{t.task_id}] {t.title} ({t.assigned_agent}): {t.description}"
            for t in task_plan.tasks
        )

        arch_str = (
            str(architecture.model_dump())
            if hasattr(architecture, "model_dump")
            else str(architecture)
        )
        req_str = "\n".join(f"- {r}" for r in requirements.functional_requirements)
        user_prompt = user_prompt_template.format(
            project_name=state.get("project_name", "AI Project"),
            architecture=arch_str,
            requirements=req_str,
            tasks=task_summary,
            code_artifacts=code_summary,
            deterministic_findings="None",
            user_context=f"user_input: {state.get('user_input', '')}",
        )

        qa_result: Optional[QAResult] = None
        while attempt < remaining_attempts:
            prompt_to_use = user_prompt
            if attempt > 0:
                prompt_to_use = revision_prompt_template.format(
                    error_message=f"{last_error_type}: {last_error_message}",
                    project_name=state.get("project_name", "AI Project"),
                    architecture=arch_str,
                    requirements=req_str,
                    tasks=task_summary,
                    code_artifacts=code_summary,
                    deterministic_findings="None",
                    user_context=f"user_input: {state.get('user_input', '')}",
                )

            try:
                qa_result = self.llm_client.generate_structured(
                    prompt=prompt_to_use,
                    response_model=QAResult,
                    system_prompt=system_prompt,
                    model_name=self.model_name,
                )

                # Validate non-empty test artifacts and test plan
                if not qa_result.test_artifacts or not qa_result.test_plan.strategy.strip():
                    raise ValueError("QAAgent: Generated test_plan or test_artifacts is empty")

                break

            except Exception as exc:
                attempt += 1
                last_error_message = str(exc)
                is_validation = isinstance(exc, (ValueError, TypeError))
                last_error_type = (
                    "validation_failure" if is_validation else "unhandled_exception"
                )
                import traceback
                last_traceback = traceback.format_exc()

                if attempt < remaining_attempts and not is_validation:
                    backoff_delay = 2.0 ** attempt
                    self.sleep_fn(backoff_delay)

        # Exhaustion path when LLM fails
        if qa_result is None:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type=last_error_type,
                error_message=f"Exhausted {remaining_attempts} attempts without valid QA result. Last error ({last_error_type}): {last_error_message}",
                traceback_str=last_traceback,
                attempt_count=attempt,
            )

        # Outside LLM retry loop: execute test runner and build return.
        # A runner exception goes straight to exhaustion return without LLM regeneration.
        try:
            return self._evaluate_and_build_return(
                state=state,
                started_at=started_at,
                qa_result=qa_result,
                code_artifacts=code_artifacts,
                task_plan=task_plan,
            )
        except Exception as exc:
            import traceback
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="test_runner_error",
                error_message=f"Test runner execution failed: {exc}",
                traceback_str=traceback.format_exc(),
                attempt_count=attempt,
            )

    def _get_effective_max_retries(self, state: EngineeringState) -> int:
        """Resolve effective max retries ceiling for QAAgent."""
        max_retries_map = state.get("max_retries") or {}
        limit = max_retries_map.get(self.agent_name, self.max_retries)
        try:
            val = int(limit)
            return val if val > 0 else DEFAULT_MAX_RETRIES
        except (TypeError, ValueError):
            return DEFAULT_MAX_RETRIES

    def _evaluate_and_build_return(
        self,
        state: EngineeringState,
        started_at: str,
        qa_result: QAResult,
        code_artifacts: Dict[str, CodeArtifact],
        task_plan: TaskPlan,
    ) -> Dict[str, Any]:
        """Execute test runner, version artifacts, and build return dictionary.

        Conditionally routes to ReviewerAgent on pass or DebugAgent on failure.
        """
        completed_at = _now_iso()
        existing_test_artifacts = state.get("test_artifacts") or {}

        # 1. Version and stamp test artifacts
        updated_test_artifacts: Dict[str, TestArtifact] = {}
        for art in qa_result.test_artifacts:
            existing = existing_test_artifacts.get(art.file_path)
            if existing is not None:
                existing_ver = getattr(existing, "version", 1)
                if existing_ver is None and isinstance(existing, dict):
                    existing_ver = existing.get("version", 1)
                art.version = (existing_ver or 1) + 1
            else:
                art.version = 1

            art.produced_by = self.agent_name
            art.produced_at = completed_at
            updated_test_artifacts[art.file_path] = art

        # 2. Version and stamp test plan
        test_plan = qa_result.test_plan
        existing_tp = state.get("test_plan")
        if existing_tp is not None:
            existing_ver = getattr(existing_tp, "version", 1)
            if existing_ver is None and isinstance(existing_tp, dict):
                existing_ver = existing_tp.get("version", 1)
            test_plan.version = (existing_ver or 1) + 1
        else:
            test_plan.version = 1

        test_plan.produced_by = self.agent_name
        test_plan.produced_at = completed_at

        # 3. Execute tests via required test runner
        execution_report = self.test_runner.run_tests(code_artifacts, updated_test_artifacts)

        # 4. Check if test failure detected
        test_failed = not execution_report.passed

        project_name = state.get("project_name", "")
        scratchpad_summary = {
            "project_name": project_name,
            "test_execution": {
                "passed": execution_report.passed,
                "total_tests": execution_report.total_tests,
                "passed_tests": execution_report.passed_tests,
                "failed_tests": execution_report.failed_tests,
                "duration_seconds": execution_report.duration_seconds,
                "failing_tests": execution_report.failing_tests,
                "coverage_percentage": execution_report.coverage_percentage,
            },
            "ai_findings": qa_result.ai_findings,
        }

        # Reset retry_counts["QAAgent"] = 0 on BOTH qa_complete and debug_required
        updated_retry_counts = dict(state.get("retry_counts") or {})
        updated_retry_counts[self.agent_name] = 0

        if test_failed:
            # On test failure, append ErrorRecord with error_type="other"
            # message prefixed "test_failure:", including failing test names and runner output truncated to 2000 chars.
            failing_names = (
                ", ".join(execution_report.failing_tests)
                if execution_report.failing_tests
                else "unknown"
            )
            truncated_output = (execution_report.output or "")[:2000]
            error_msg = f"test_failure: failing tests: [{failing_names}]. Output:\n{truncated_output}"

            error_record = ErrorRecord(
                error_id=str(uuid.uuid4()),
                agent=self.agent_name,
                stage=STATUS_DEBUG_REQUIRED,
                error_type="other",
                message=error_msg,
                traceback="",
                occurred_at=completed_at,
                resolved=False,
            )

            # Note: Do NOT mark QA tasks completed on test failure
            return {
                "test_plan": test_plan,
                "test_artifacts": updated_test_artifacts,
                "workflow_status": STATUS_DEBUG_REQUIRED,
                "next_agent": "DebugAgent",
                "current_agent": self.agent_name,
                "errors": [error_record],
                "retry_counts": updated_retry_counts,
                "agent_scratchpad": {self.agent_name: str(scratchpad_summary)},
                "state_version": state.get("state_version", 0) + 1,
                "updated_at": completed_at,
            }

        # 5. Success path -> ReviewerAgent
        # Mark QA tasks completed only on a passing run (deep-copy task_plan to avoid mutating input state)
        updated_task_plan = task_plan.model_copy(deep=True)
        for task in updated_task_plan.tasks:
            if task.assigned_agent == self.agent_name:
                task.status = "completed"

        current_forward_stage = state.get("forward_stage", 0)
        new_forward_stage = max(current_forward_stage, 6)

        return {
            "test_plan": test_plan,
            "test_artifacts": updated_test_artifacts,
            "task_plan": updated_task_plan,
            "workflow_status": STATUS_QA_COMPLETE,
            "next_agent": "ReviewerAgent",
            "current_agent": self.agent_name,
            "forward_stage": new_forward_stage,
            "retry_counts": updated_retry_counts,
            "checkpoint_stage": "qa_complete",
            "checkpoints": {"qa_complete": completed_at},
            "agent_scratchpad": {self.agent_name: str(scratchpad_summary)},
            "state_version": state.get("state_version", 0) + 1,
            "updated_at": completed_at,
        }

    def _build_exhaustion_return(
        self,
        state: EngineeringState,
        started_at: str,
        error_type: str,
        error_message: str,
        traceback_str: str,
        attempt_count: int,
    ) -> Dict[str, Any]:
        """Build exhaustion state update triggering HumanApprovalNode pause."""
        completed_at = _now_iso()
        effective_max_retries = self._get_effective_max_retries(state)

        updated_retry_counts = dict(state.get("retry_counts") or {})
        updated_retry_counts[self.agent_name] = effective_max_retries

        human_notes = (
            f"QAAgent failed after reaching max retries ({effective_max_retries}). "
            f"Reason: {error_message}. Human approval is required to continue."
        )

        error_record = ErrorRecord(
            error_id=str(uuid.uuid4()),
            agent=self.agent_name,
            stage=str(state.get("workflow_status") or "qa_exhaustion"),
            error_type="retry_exhausted",
            message=error_message,
            traceback=traceback_str,
            occurred_at=completed_at,
            resolved=False,
        )

        duration = (
            datetime.fromisoformat(completed_at) - datetime.fromisoformat(started_at)
        ).total_seconds()

        metadata = AgentExecutionMetadata(
            agent_name=self.agent_name,
            started_at=started_at,
            completed_at=completed_at,
            duration_seconds=duration,
            tokens_used=0,
            model_calls=attempt_count,
            status="failed",
            notes=error_message,
        )

        # Invariant: workflow_status is preserved unchanged
        return {
            "current_agent": self.agent_name,
            "next_agent": self.agent_name,
            "human_approval_required": True,
            "human_approval_notes": human_notes,
            "errors": [error_record],
            "retry_counts": updated_retry_counts,
            "execution_metadata": {self.agent_name: metadata},
            "agent_scratchpad": {self.agent_name: f"Exhaustion: {error_message}"},
            "state_version": state.get("state_version", 0) + 1,
            "updated_at": completed_at,
        }
