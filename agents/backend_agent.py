"""
agents/backend_agent.py

BackendAgent: Concrete pipeline agent that implements all backend ImplementationTask
entries from task_plan by generating server-side code artifacts and writing them
into code_artifacts.

Source of truth:
  - design.md Section 1.4 (BackendAgent contract)
  - design.md Section 2 (State Ownership Matrix)
  - design.md Section 6.1 (Folder ownership: agents/backend_agent.py)
  - requirements.md Requirement 1 (Run Metadata), Requirement 6 (CodeArtifacts),
    Requirement 12 (Error Tracking), Requirement 13 (Retry and Escalation Tracking),
    Requirement 14 (Metadata), Requirement 21 criterion 6 (forward_stage idempotency),
    Requirement 21 criterion 7 (total_invocations).
  - workflow-design-revised.md Section 3.0, 3.3, 3.9, 3.10.
"""

