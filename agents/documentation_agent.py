from __future__ import annotations

import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Dict, List, Literal, Optional, Union

from pydantic import BaseModel, Field

from agents.base_agent import BaseAgent, DEFAULT_MAX_RETRIES, strip_metadata_header
from state.engineering_state import EngineeringState
from state.models import (
    AgentExecutionMetadata,
    CodeArtifact,
    DeploymentArtifact,
    DocumentationArtifact,
    ErrorRecord,
    ProductRequirements,
    ReviewReport,
    SystemArchitecture,
    TestPlan,
)
from state.validators import WORKFLOW_STATUS_VALUES
from tools.documentation.markdown_linter import LintReport, MarkdownLinter
from tools.shared.llm_client import LLMClient

# Local status constants (guarded to ensure membership in WORKFLOW_STATUS_VALUES)
STATUS_DOCUMENTATION_COMPLETE: str = "documentation_complete"
if STATUS_DOCUMENTATION_COMPLETE not in WORKFLOW_STATUS_VALUES:
    raise ImportError("Local status constant is not a valid workflow status")

_DEFAULT_PROMPTS_DIR = Path(__file__).resolve().parent.parent / "prompts" / "documentation"


def _now_iso() -> str:
    """Return the current UTC timestamp formatted as an ISO 8601 string."""
    return datetime.now(timezone.utc).isoformat()


class DraftDocumentationArtifact(BaseModel):
    """Draft documentation artifact generated by LLM prior to agent metadata stamping."""

    file_path: str = Field(description="Relative path of documentation artifact (e.g. README.md)")
    content: str = Field(description="Complete markdown content of the documentation file")
    doc_type: Literal[
        "readme",
        "onboarding",
        "architecture",
        "api_reference",
        "deployment_guide",
        "maintenance",
        "other",
    ] = Field(description="Category of documentation artifact")


class DocumentationOutput(BaseModel):
    """Structured container model for documentation artifacts returned by LLM."""

    artifacts: List[DraftDocumentationArtifact] = Field(
        default_factory=list,
        description="List of draft documentation artifacts",
    )
    summary: str = Field(
        default="",
        description="Summary of documentation generated and coverage notes",
    )


class DocumentationAgent(BaseAgent):
    """Concrete agent that generates and lints project documentation artifacts."""

    def __init__(
        self,
        model_name: str,
        llm_client: LLMClient,
        linter: MarkdownLinter,
        max_retries: int = DEFAULT_MAX_RETRIES,
        sleep_fn: Callable[[float], None] = time.sleep,
        prompts_dir: Optional[Union[Path, str]] = None,
    ) -> None:
        """
        Args:
            model_name: Model identifier (e.g. from configs/agents.yaml).
            llm_client: Structured LLM client conforming to LLMClient Protocol.
            linter: Required markdown linting tool (Protocol).
            max_retries: Default retry ceiling passed to BaseAgent constructor.
            sleep_fn: Injectable sleep function for backoff timing.
            prompts_dir: Directory containing prompt templates (defaults to prompts/documentation).
        """
        if not model_name or not isinstance(model_name, str) or not model_name.strip():
            raise ValueError("DocumentationAgent: model_name must be a non-empty string")
        if llm_client is None:
            raise ValueError("DocumentationAgent: llm_client must not be None")
        if linter is None:
            raise ValueError("DocumentationAgent: linter must not be None")

        super().__init__(agent_name="DocumentationAgent", max_retries=max_retries)
        self.model_name = model_name
        self.llm_client = llm_client
        self.linter: MarkdownLinter = linter
        self.sleep_fn = sleep_fn
        self.prompts_dir = Path(prompts_dir) if prompts_dir else _DEFAULT_PROMPTS_DIR

    def _load_prompt(self, filename: str) -> str:
        """Read a prompt file and strip its metadata header block."""
        filepath = self.prompts_dir / filename
        if not filepath.exists():
            raise FileNotFoundError(f"Prompt template file not found: {filepath}")
        raw_text = filepath.read_text(encoding="utf-8")
        return strip_metadata_header(raw_text)

    def _get_effective_max_retries(self, state: EngineeringState) -> int:
        """Resolve effective max retries ceiling for DocumentationAgent."""
        max_retries_map = state.get("max_retries") or {}
        limit = max_retries_map.get(self.agent_name, self.max_retries)
        try:
            val = int(limit)
            return val if val > 0 else DEFAULT_MAX_RETRIES
        except (TypeError, ValueError):
            return DEFAULT_MAX_RETRIES

    def execute(self, state: EngineeringState) -> Dict[str, Any]:
        """Generate documentation artifacts, validate markdown structure, and route to FinalProject."""
        started_at = _now_iso()
        effective_max = self._get_effective_max_retries(state)
        current_retries = (state.get("retry_counts") or {}).get(self.agent_name, 0)

        # 1. Fast-fail if retry limit already reached prior to execution
        if current_retries >= effective_max:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="retry_exhausted",
                error_message=(
                    f"Retry limit already reached ({current_retries}/{effective_max}) "
                    f"for {self.agent_name} before execution."
                ),
                traceback_str="",
                attempt_count=0,
            )

        requirements: Optional[ProductRequirements] = state.get("requirements")
        architecture: Optional[SystemArchitecture] = state.get("architecture")

        # 2. Fast-fail if mandatory inputs are missing
        if requirements is None or architecture is None:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type="validation_failure",
                error_message="Missing or empty requirements or architecture",
                traceback_str="",
                attempt_count=0,
            )

        system_prompt = self._load_prompt("system_prompt.md")
        user_prompt_template = self._load_prompt("user_prompt_template.md")
        revision_prompt_template = self._load_prompt("revision_prompt.md")

        remaining_attempts = max(1, effective_max - current_retries)
        last_error_message = ""
        last_error_type = "validation_failure"
        last_traceback = ""
        last_artifacts_str = "None"
        attempt = 0

        # Build context strings for prompts
        project_name = state.get("project_name", "")
        reqs_str = (
            str(requirements.model_dump())
            if hasattr(requirements, "model_dump")
            else str(requirements)
        )
        arch_str = (
            str(architecture.model_dump())
            if hasattr(architecture, "model_dump")
            else str(architecture)
        )
        code_artifacts = state.get("code_artifacts") or {}
        code_summary = (
            "\n".join(f"- {p} ({a.artifact_type})" for p, a in sorted(code_artifacts.items()))
            if code_artifacts
            else "None"
        )
        test_plan = state.get("test_plan")
        test_plan_str = (
            str(test_plan.model_dump())
            if hasattr(test_plan, "model_dump")
            else str(test_plan)
            if test_plan
            else "None"
        )
        deploy_artifacts = state.get("deployment_artifacts") or {}
        deploy_summary = (
            "\n".join(f"- {p} ({a.artifact_type})" for p, a in sorted(deploy_artifacts.items()))
            if deploy_artifacts
            else "None"
        )

        initial_user_prompt = user_prompt_template.format(
            project_name=project_name,
            requirements=reqs_str,
            architecture=arch_str,
            code_artifacts=code_summary,
            test_plan=test_plan_str,
            deployment_artifacts=deploy_summary,
        )

        existing_artifacts = state.get("documentation_artifacts") or {}
        doc_output: Optional[DocumentationOutput] = None
        validated_artifacts: Dict[str, DocumentationArtifact] = {}

        # 3. LLM retry loop
        while attempt < remaining_attempts:
            if attempt == 0:
                current_prompt = initial_user_prompt
            else:
                current_prompt = revision_prompt_template.format(
                    error_message=last_error_message,
                    previous_artifacts=last_artifacts_str,
                    project_name=project_name,
                    requirements=reqs_str,
                    architecture=arch_str,
                )

            try:
                candidate: DocumentationOutput = self.llm_client.generate_structured(
                    prompt=current_prompt,
                    system_prompt=system_prompt,
                    response_model=DocumentationOutput,
                    model_name=self.model_name,
                )

                # Validation inside retry loop:
                # Must contain at minimum: readme, architecture, api_reference, deployment_guide (design.md Section 1.10)
                if not candidate.artifacts:
                    raise ValueError("DocumentationAgent: Generated artifacts list cannot be empty")

                present_types = {a.doc_type for a in candidate.artifacts}
                required_types = {"readme", "architecture", "api_reference", "deployment_guide"}
                missing = required_types - present_types
                if missing:
                    raise ValueError(
                        f"DocumentationAgent: Missing required documentation types: {sorted(missing)}"
                    )

                for art in candidate.artifacts:
                    if not art.file_path or not art.file_path.strip():
                        raise ValueError("DocumentationAgent: Artifact file_path cannot be empty")
                    if not art.content or not art.content.strip():
                        raise ValueError(f"DocumentationAgent: Artifact content cannot be empty for {art.file_path}")

                # Record previous artifacts for revision prompt in case linter fails
                last_artifacts_str = "\n\n".join(
                    f"--- {art.file_path} ({art.doc_type}) ---\n{art.content}"
                    for art in candidate.artifacts
                )

                # Build candidate DocumentationArtifact objects for linter
                timestamp = _now_iso()
                candidate_artifacts: Dict[str, DocumentationArtifact] = {}
                for draft in candidate.artifacts:
                    existing = existing_artifacts.get(draft.file_path)
                    existing_ver = getattr(existing, "version", 1) if existing else 1
                    if existing_ver is None and isinstance(existing, dict):
                        existing_ver = existing.get("version", 1)
                    version = (existing_ver or 1) + 1 if existing else 1

                    candidate_artifacts[draft.file_path] = DocumentationArtifact(
                        file_path=draft.file_path,
                        content=draft.content,
                        doc_type=draft.doc_type,
                        produced_by=self.agent_name,
                        produced_at=timestamp,
                        version=version,
                    )

                # Tool execution: a tool EXCEPTION bypasses LLM retry loop and goes straight to exhaustion
                try:
                    lint_report: LintReport = self.linter.lint_documentation(
                        documentation_artifacts=candidate_artifacts
                    )
                except Exception as tool_exc:
                    import traceback

                    return self._build_exhaustion_return(
                        state=state,
                        started_at=started_at,
                        error_type="unhandled_exception",
                        error_message=f"Markdown linter tool exception: {tool_exc}",
                        traceback_str=traceback.format_exc(),
                        attempt_count=attempt,
                    )

                # Tool report failure: feeds LLM retry loop as a validation_failure
                if not lint_report.passed:
                    err_msg = "; ".join(lint_report.errors or ["Markdown linting failed"])
                    raise ValueError(f"Markdown linting failed: {err_msg}")

                # Success: valid output and report passed
                doc_output = candidate
                validated_artifacts = candidate_artifacts
                break

            except Exception as exc:
                attempt += 1
                last_error_message = str(exc)
                is_validation = isinstance(exc, (ValueError, TypeError))
                last_error_type = (
                    "validation_failure" if is_validation else "unhandled_exception"
                )
                import traceback

                last_traceback = traceback.format_exc()

                if attempt < remaining_attempts and not is_validation:
                    backoff_delay = 2.0 ** attempt
                    self.sleep_fn(backoff_delay)

        # 4. Handle exhaustion if LLM fails
        if doc_output is None:
            return self._build_exhaustion_return(
                state=state,
                started_at=started_at,
                error_type=last_error_type,
                error_message=(
                    f"Exhausted {remaining_attempts} attempts without valid documentation. "
                    f"Last error ({last_error_type}): {last_error_message}"
                ),
                traceback_str=last_traceback,
                attempt_count=attempt,
            )

        completed_at = _now_iso()
        duration = (
            datetime.fromisoformat(completed_at) - datetime.fromisoformat(started_at)
        ).total_seconds()

        # 5. Success path
        current_forward_stage = state.get("forward_stage", 0)
        new_forward_stage = max(current_forward_stage, 9)
        updated_retry_counts = dict(state.get("retry_counts") or {})
        updated_retry_counts[self.agent_name] = 0

        metadata = AgentExecutionMetadata(
            agent_name=self.agent_name,
            started_at=started_at,
            completed_at=completed_at,
            duration_seconds=duration,
            tokens_used=0,
            model_calls=attempt + 1,
            status="completed",
            notes="Documentation artifacts successfully generated and linted",
        )

        return {
            "documentation_artifacts": validated_artifacts,
            "workflow_status": STATUS_DOCUMENTATION_COMPLETE,
            "current_agent": self.agent_name,
            "next_agent": "FinalProjectAgent",
            "forward_stage": new_forward_stage,
            "checkpoint_stage": "documentation_complete",
            "checkpoints": {"documentation_complete": completed_at},
            "retry_counts": updated_retry_counts,
            "execution_metadata": {self.agent_name: metadata},
            "agent_scratchpad": {self.agent_name: doc_output.summary or "Documentation generated"},
            "state_version": state.get("state_version", 0) + 1,
            "updated_at": completed_at,
        }

    def _build_exhaustion_return(
        self,
        state: EngineeringState,
        started_at: str,
        error_type: str,
        error_message: str,
        traceback_str: str,
        attempt_count: int,
    ) -> Dict[str, Any]:
        """Build exhaustion state update triggering HumanApprovalNode pause."""
        completed_at = _now_iso()
        effective_max = self._get_effective_max_retries(state)

        updated_retry_counts = dict(state.get("retry_counts") or {})
        updated_retry_counts[self.agent_name] = effective_max

        human_notes = (
            f"DocumentationAgent failed after reaching max retries ({effective_max}). "
            f"Reason: {error_message}. Human approval is required to continue."
        )

        error_record = ErrorRecord(
            error_id=str(uuid.uuid4()),
            agent=self.agent_name,
            stage=str(state.get("workflow_status") or "documentation_exhaustion"),
            error_type="retry_exhausted",
            message=error_message,
            traceback=traceback_str,
            occurred_at=completed_at,
            resolved=False,
        )

        duration = (
            datetime.fromisoformat(completed_at) - datetime.fromisoformat(started_at)
        ).total_seconds()

        metadata = AgentExecutionMetadata(
            agent_name=self.agent_name,
            started_at=started_at,
            completed_at=completed_at,
            duration_seconds=duration,
            tokens_used=0,
            model_calls=attempt_count,
            status="failed",
            notes=error_message,
        )

        # Invariant: workflow_status is preserved unchanged
        return {
            "current_agent": self.agent_name,
            "next_agent": self.agent_name,
            "human_approval_required": True,
            "human_approval_notes": human_notes,
            "errors": [error_record],
            "retry_counts": updated_retry_counts,
            "execution_metadata": {self.agent_name: metadata},
            "agent_scratchpad": {self.agent_name: f"Exhaustion: {error_message}"},
            "state_version": state.get("state_version", 0) + 1,
            "updated_at": completed_at,
        }
        